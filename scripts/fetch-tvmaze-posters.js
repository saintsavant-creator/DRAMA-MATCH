#!/usr/bin/env node
/**
 * Fetch poster images from TVmaze API for shows missing from poster-paths.js.
 * TVmaze API is free and requires no authentication.
 * Rate limit: 20 requests per 10 seconds.
 *
 * Usage: node scripts/fetch-tvmaze-posters.js
 * Output: data/tvmaze-posters.js (map of showId -> TVmaze image URL)
 */

const https = require('https');
const http = require('http');
const fs = require('fs');
const path = require('path');

// Load existing poster paths
const { POSTER_PATHS } = require('../data/poster-paths');

// Load the full catalog via recommendation engine (builds allShows)
const engine = require('../data/recommendation-engine');
const catalog = engine.getAllShows();

// Find shows missing poster coverage
const missingShows = catalog.filter(show => !POSTER_PATHS[show.id]);
console.log(`Total catalog: ${catalog.length}`);
console.log(`Already have TMDB posters: ${catalog.length - missingShows.length}`);
console.log(`Missing posters: ${missingShows.length}`);

// TVmaze single search endpoint
function searchTVmaze(title, year) {
  return new Promise((resolve) => {
    // Build query — include year for disambiguation
    const query = encodeURIComponent(year ? `${title} ${year}` : title);
    const url = `https://api.tvmaze.com/singlesearch/shows?q=${query}`;

    const req = https.get(url, { timeout: 8000 }, (res) => {
      let data = '';
      res.on('data', chunk => { data += chunk; });
      res.on('end', () => {
        if (res.statusCode === 200) {
          try {
            const result = JSON.parse(data);
            const imageUrl = result.image && (result.image.medium || result.image.original);
            resolve(imageUrl || null);
          } catch {
            resolve(null);
          }
        } else {
          resolve(null);
        }
      });
    });
    req.on('error', () => resolve(null));
    req.on('timeout', () => { req.destroy(); resolve(null); });
  });
}

// Process in batches to respect rate limits
async function processBatch(shows, batchSize, delayMs) {
  const results = {};
  let found = 0;
  let notFound = 0;

  for (let i = 0; i < shows.length; i += batchSize) {
    const batch = shows.slice(i, i + batchSize);
    const batchNum = Math.floor(i / batchSize) + 1;
    const totalBatches = Math.ceil(shows.length / batchSize);

    const promises = batch.map(async (show) => {
      // Clean up title for search (remove year suffixes, etc.)
      let searchTitle = show.title;
      const url = await searchTVmaze(searchTitle, show.year);
      if (url) {
        results[show.id] = url;
        found++;
      } else {
        // Try without year
        const url2 = await searchTVmaze(searchTitle);
        if (url2) {
          results[show.id] = url2;
          found++;
        } else {
          notFound++;
        }
      }
    });

    await Promise.all(promises);
    console.log(`Batch ${batchNum}/${totalBatches}: ${found} found, ${notFound} not found (${i + batch.length}/${shows.length})`);

    // Rate limit delay (skip on last batch)
    if (i + batchSize < shows.length) {
      await new Promise(r => setTimeout(r, delayMs));
    }
  }

  return results;
}

async function main() {
  console.log('\nFetching poster URLs from TVmaze...\n');

  // Process 15 at a time with 10-second delays (safe under 20/10s limit)
  const results = await processBatch(missingShows, 15, 10000);

  const foundCount = Object.keys(results).length;
  console.log(`\nDone! Found ${foundCount}/${missingShows.length} poster URLs (${Math.round(foundCount/missingShows.length*100)}% coverage)`);

  // Write results to file
  const outputPath = path.join(__dirname, '..', 'data', 'tvmaze-posters.js');
  const entries = Object.entries(results)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, url]) => `  '${id}': '${url}'`)
    .join(',\n');

  const fileContent = `/**
 * TVmaze poster URLs for shows not covered by TMDB poster-paths.
 * Auto-generated by scripts/fetch-tvmaze-posters.js on ${new Date().toISOString().split('T')[0]}.
 * ${foundCount} entries.
 */

const TVMAZE_POSTERS = {
${entries}
};

module.exports = { TVMAZE_POSTERS };
`;

  fs.writeFileSync(outputPath, fileContent);
  console.log(`\nWritten to ${outputPath}`);
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
